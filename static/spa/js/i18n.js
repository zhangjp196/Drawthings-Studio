  const langRef = Vue.ref(cur);

  const listeners = [];

  function t(key, ...args) {
    const lang = langRef.value;
    let s = dict[lang][key];
    if (s === undefined) s = dict.zh[key];
    if (s === undefined) s = key;
    args.forEach((a, i) => {
      s = s.split('{' + i + '}').join(a);
    });
    return s;
  }

